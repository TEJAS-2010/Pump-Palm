import test from 'node:test';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {once} from 'node:events';
import {mkdtemp, rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';

test('accounts, isolation, field edits, device pairing, live telemetry and video',async t=>{
  const dir=await mkdtemp(join(tmpdir(),'pump-test-'));
  const server=spawn(process.execPath,['server.mjs'],{env:{...process.env,NODE_ENV:'test',PORT:'0',DATABASE_URL:'',SQLITE_PATH:join(dir,'test.db')},stdio:['ignore','pipe','inherit']});
  t.after(async()=>{
    if(server.exitCode===null){const done=once(server,'exit');server.kill();await done;}
    await rm(dir,{recursive:true,force:true});
  });
  const [chunk]=await once(server.stdout,'data');
  const port=Number(String(chunk).match(/listening on (\d+)/)?.[1]);
  assert.ok(port);
  let cookie;
  async function call(path,method='GET',body,headers={}){
    const response=await fetch('http://127.0.0.1:'+port+path,{method,headers:{...(cookie?{Cookie:cookie}:{}),...(body?{'Content-Type':'application/json'}:{}),...headers},body:body?JSON.stringify(body):undefined});
    return [response,await response.json()];
  }
  assert.equal((await call('/api/fields','POST',{country:'AE',lat:25.5,lon:55.55}))[0].status,401);
  const first={email:'grower@example.test',password:'field-tests-9833'};
  let [res]=await call('/api/auth/register','POST',first);
  assert.equal(res.status,201);
  assert.match(res.headers.get('set-cookie'),/HttpOnly/);
  cookie=res.headers.get('set-cookie').split(';')[0];
  const initial={name:'Test field',lat:25.5,lon:55.55,country:'AE',polygon:[[25.5,55.55],[25.501,55.55],[25.501,55.552]],dry:18,wet:29,maxEc:3,eventLimit:150,heat:39,previous:['Tomato','Zucchini']};
  const [created,field]=await call('/api/fields','POST',initial);
  assert.equal(created.status,201);
  assert.deepEqual(field.polygon,initial.polygon);
  const base='/api/fields/'+field.id;
  let [planStatus, saved]=await call(base+'/plan','PUT',{priority:'cover',budget:400,base:450,legume:390,mixed:300});
  assert.equal(planStatus.status,200);
  assert.equal(saved.plan.budget,400);
  const [edited,updated]=await call(base,'PUT',{...initial,name:'Updated'});
  assert.equal(edited.status,200);
  assert.equal(updated.plan.priority,'cover');
  const [,device]=await call(base+'/devices','POST',{label:'North probe'});
  assert.match(device.token,/^[a-f0-9]{64}$/);
  const data={timestamp:new Date().toISOString(),moisture_pct:17.2,ecw_dsm:3.5,litres:161.1,soil_temp_c:33.2};
  const [unauth]=await call('/api/telemetry','POST',data);
  assert.equal(unauth.status,401);
  const headers={Authorization:'Bearer '+device.token};
  assert.equal((await call('/api/telemetry','POST',data,headers))[0].status,202);
  assert.equal((await call('/api/telemetry','POST',data,headers))[0].status,202);
  let [,rows]=await call(base+'/readings');
  assert.equal(rows.length,1);
  assert.equal(rows[0].ecw_dsm,3.5);
  assert.equal(rows[0].origin,'arduino');
  const raw = {timestamp:new Date(Date.now()+1000).toISOString(),raw_adc:3577,probe_calibration:'esp32-probe-2026-11-14-v1'};
  assert.equal((await call('/api/telemetry','POST',raw,headers))[0].status,202);
  [,rows]=await call(base+'/readings');
  assert.equal(rows[0].wetness_index,17.7);
  assert.equal(rows[0].moisture_pct,null);
  assert.equal(rows[0].raw_adc,3577);
  assert.equal((await call('/api/telemetry','POST',{...raw,raw_adc:4096},headers))[0].status,400);
  const [,newToken]=await call(base+'/devices/'+device.id+'/rotate','POST');
  assert.notEqual(newToken.token,device.token);
  assert.equal((await call('/api/telemetry','POST',data,headers))[0].status,401);
  const [invalid]=await call(base+'/import','POST',{rows:[{...data,moisture_pct:101}]});
  assert.equal(invalid.status,400);
  const [imported]=await call(base+'/import','POST',{rows:[data]});
  assert.equal(imported.status,200);
  [,rows]=await call(base+'/readings');
  assert.deepEqual(new Set(rows.map(row=>row.origin)),new Set(['csv','arduino']));
  const [catalog,catalogue]=await call('/api/catalog');
  assert.equal(catalog.status,200);
  assert.ok(catalogue.catalog.ecostress);
  const [second]=await call('/api/auth/register','POST',{email:'second@example.test',password:'field-tests-5678'});
  cookie=second.headers.get('set-cookie').split(';')[0];
  assert.equal((await call(base+'/readings'))[0].status,404);
  assert.equal((await call(base+'/plan','PUT',{priority:'water'}))[0].status,404);
  const [,list]=await call('/api/fields');
  assert.equal(list.length,0);
  const [minimalStatus,minimal]=await call('/api/fields','POST',{country:'AE',lat:25.54,lon:55.59});
  assert.equal(minimalStatus.status,201);
  assert.equal(minimal.name,'My field');
  assert.equal(minimal.crop,null);
  assert.equal(minimal.dry,null);
  assert.equal(minimal.ece,null);
  assert.deepEqual((await call('/api/fields/'+minimal.id+'/readings'))[1],[]);
  const otherGrowers=await Promise.all(['a','b','c','d'].map(async (label,index)=>{
    const [registration]=await call('/api/auth/register','POST',{email:label+'@example.test',password:'field-test-concurrent'});
    assert.equal(registration.status,201);
    const headers={Cookie:registration.headers.get('set-cookie').split(';')[0]};
    const [creation,ownField]=await call('/api/fields','POST',{country:'AE',lat:25.54+index/100,lon:55.59},headers);
    assert.equal(creation.status,201);
    assert.equal((await call('/api/fields/'+minimal.id+'/readings','GET',null,headers))[0].status,404);
    assert.deepEqual((await call('/api/fields','GET',null,headers))[1].map(row=>row.id),[ownField.id]);
    return ownField.id;
  }));
  assert.equal(new Set(otherGrowers).size,4);
  await call('/api/logout','POST');
  assert.equal((await call('/api/me'))[0].status,401);
  const [signIn]=await call('/api/auth/login','POST',first);
  assert.equal(signIn.status,200);
  const publicPage=await fetch('http://127.0.0.1:'+port+'/showcase.html');
  assert.equal(publicPage.status,200);
  assert.match(await publicPage.text(),/UMM AL QUWAIN/);
  const lab=await fetch('http://127.0.0.1:'+port+'/soil-lab.html');
  assert.match(await lab.text(),/SYNTHETIC TRAINING DATA/);
  const model=await fetch('http://127.0.0.1:'+port+'/synthetic-vwc.json').then(response=>response.json());
  assert.equal(model.provenance,'synthetic_only');
  assert.equal(model.held_out.samples,12);
  const video=await fetch('http://127.0.0.1:'+port+'/videos/heat.mp4',{headers:{Range:'bytes=0-31'}});
  assert.equal(video.status,206);
  assert.match(video.headers.get('content-type'),/video\/mp4/);
});
